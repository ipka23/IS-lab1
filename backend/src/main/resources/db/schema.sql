BEGIN;

DROP FUNCTION IF EXISTS golden_palm_sum();
DROP FUNCTION IF EXISTS movie_latest();
DROP FUNCTION IF EXISTS movies_usa_box_office_greater(INTEGER);
DROP FUNCTION IF EXISTS screenwriters_without_oscars();
DROP FUNCTION IF EXISTS award_long_movies(INTEGER, INTEGER);

DROP TABLE IF EXISTS movie CASCADE;
DROP TABLE IF EXISTS person CASCADE;

CREATE TABLE person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL CHECK (name <> ''),
    eye_color VARCHAR(20),
    hair_color VARCHAR(20) NOT NULL,
    location_x DOUBLE PRECISION,
    location_y BIGINT,
    location_name VARCHAR(255) CHECK (location_name IS NULL OR location_name <> ''),
    weight INTEGER CHECK (weight IS NULL OR weight > 0),
    nationality VARCHAR(20) NOT NULL
);

CREATE TABLE movie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL CHECK (name <> ''),
    x INTEGER NOT NULL CHECK (x > -404),
    y INTEGER NOT NULL CHECK (y <= 851),
    creation_date TIMESTAMP NOT NULL DEFAULT now(),
    oscars_count INTEGER NOT NULL CHECK (oscars_count > 0),
    budget INTEGER NOT NULL CHECK (budget > 0),
    total_box_office REAL NOT NULL CHECK (total_box_office > 0),
    mpaa_rating VARCHAR(10),
    director_id BIGINT REFERENCES person (id),
    screenwriter_id BIGINT REFERENCES person (id),
    operator_id BIGINT NOT NULL REFERENCES person (id),
    length INTEGER NOT NULL CHECK (length > 0),
    golden_palm_count INTEGER NOT NULL CHECK (golden_palm_count > 0),
    usa_box_office INTEGER NOT NULL CHECK (usa_box_office > 0),
    tagline VARCHAR(255) NOT NULL,
    genre VARCHAR(20) NOT NULL
);

CREATE FUNCTION golden_palm_sum() RETURNS BIGINT AS $$
SELECT COALESCE(SUM(golden_palm_count), 0) FROM movie;
$$ LANGUAGE sql;

CREATE FUNCTION movie_latest() RETURNS SETOF movie AS $$
SELECT * FROM movie ORDER BY creation_date DESC LIMIT 1;
$$ LANGUAGE sql;

CREATE FUNCTION movies_usa_box_office_greater(p_value INTEGER) RETURNS SETOF movie AS $$
SELECT * FROM movie WHERE usa_box_office > p_value;
$$ LANGUAGE sql;

CREATE FUNCTION screenwriters_without_oscars() RETURNS SETOF person AS $$
SELECT p.* FROM person p
WHERE EXISTS (SELECT 1 FROM movie m WHERE m.screenwriter_id = p.id)
  AND NOT EXISTS (SELECT 1 FROM movie m WHERE m.screenwriter_id = p.id AND m.oscars_count > 0);
$$ LANGUAGE sql;

CREATE FUNCTION award_long_movies(p_min_length INTEGER, p_oscars INTEGER) RETURNS INTEGER AS $$
DECLARE
    updated_count INTEGER;
BEGIN
    UPDATE movie SET oscars_count = oscars_count + p_oscars WHERE length > p_min_length;
    GET DIAGNOSTICS updated_count = ROW_COUNT;
    RETURN updated_count;
END;
$$ LANGUAGE plpgsql;

COMMIT;